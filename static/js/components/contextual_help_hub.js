const faDigits = "۰۱۲۳۴۵۶۷۸۹";

function toFa(value) {
  return String(value).replace(/\d/g, (d) => faDigits[Number(d)]);
}

function normalizeRole(value) {
  const role = String(value || "").trim().toLowerCase();
  if (role.includes("stylist")) return "stylist";
  if (role.includes("customer")) return "customer";
  if (role.includes("manager") || role.includes("salon")) return "manager";
  return role;
}

